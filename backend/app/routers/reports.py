def _results_to_table(results: dict) -> str:
    """Convert a results dict to an APA-style HTML table."""
    rows = ""
    for key, value in results.items():
        if isinstance(value, dict):
            continue  # Skip nested dicts
        if isinstance(value, list):
            continue  # Skip arrays
        label = key.replace("_", " ").title()
        if isinstance(value, float):
            formatted = f"{value:.4f}" if abs(value) < 1 else f"{value:.2f}"
        else:
            formatted = html.escape(str(value))
        rows += f"<tr><td>{html.escape(label)}</td><td>{formatted}</td></tr>\n"

    return f"""
    <table>
        <tr><th>Statistic</th><th>Value</th></tr>
        {rows}
    </table>
    """


@router.post("/generate")
def generate_report(req: ReportRequest):
    """Generate an HTML report from analysis results."""
    now = datetime.utcnow().strftime("%B %d, %Y")
    author = html.escape(req.author or "PsyStat Lab User")
    title = html.escape(req.title)

    body = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{title}</title>
    {_css()}
</head>
<body>

<div class="title-page">
    <h1>{title}</h1>
    <div class="author">{author}</div>
    <div class="date">{now}</div>
    <div class="generated">Generated by PsyStat Lab — AI-powered behavioral science statistics platform</div>
</div>
"""

    # Methods section
    if req.include_methods and req.apa_results:
        body += "<h2>Method</h2>\n"
        body += "<h3>Statistical Analysis</h3>\n"
        test_types = set(r.get("test_type", "") for r in req.apa_results)
        body += f'<p>Statistical analyses were performed using PsyStat Lab. '
        body += f'The following tests were conducted: {", ".join(test_types)}. '
        body += f'Significance was evaluated at α = .05 unless otherwise noted.</p>\n'

    # Results section
    body += "<h2>Results</h2>\n"

    for section in req.sections:
        body += f"<h3>{html.escape(section.title)}</h3>\n"
        # Convert APA-style formatting
        content = section.content
        # Italicize standard stat terms
        for term in ['t', 'F', 'p', 'd', 'r', 'M', 'SD', 'N', 'n', 'df']:
            content = content.replace(f" {term} =", f" <em>{term}</em> =")
            content = content.replace(f" {term}(", f" <em>{term}</em>(")
            content = content.replace(f" {term} <", f" <em>{term}</em> <")
        body += f'<p class="no-indent">{content}</p>\n'

        if section.chart_data:
            body += f'<p class="note">[Figure: {html.escape(section.chart_data.get("title", "Chart"))}]</p>\n'

    # APA results blocks
    if req.apa_results:
        for apa in req.apa_results:
            apa_text = apa.get("apa_text", "")
            if apa_text:
                body += f'<div class="apa-result">{html.escape(apa_text)}</div>\n'

            # Include result table if raw results provided
            raw = apa.get("raw_results")
            if raw and isinstance(raw, dict):
                body += _results_to_table(raw)

    # References
    if req.include_references:
        body += "<h2>References</h2>\n"
        body += '<p class="no-indent">American Psychological Association. (2020). <em>Publication manual of the American Psychological Association</em> (7th ed.). https://doi.org/10.1037/0000165-000</p>\n'

    body += """
<div class="note" style="margin-top: 48pt; border-top: 1px solid #ddd; padding-top: 12pt;">
    This report was generated automatically by PsyStat Lab. Results should be reviewed by a qualified researcher before publication.
</div>

</body>
</html>"""

    return {
        "html": body,
        "title": req.title,
        "generated_at": now,
    }


class QuickReportRequest(BaseModel):
    """Generate a quick report from a single analysis."""
    module: str
    test_type: str
    results: dict
    apa_text: str | None = None
    author: str | None = None


@router.post("/quick")
def quick_report(req: QuickReportRequest):
    """Generate a single-analysis report."""
    sections = [
        ReportSection(
            title=f"{req.module} — {req.test_type}",
            content=req.apa_text or "Analysis results are presented below.",
        )
    ]

    apa_results = []
    if req.apa_text:
        apa_results.append({
            "test_type": req.test_type,
            "apa_text": req.apa_text,
            "raw_results": req.results,
        })

    report_req = ReportRequest(
        title=f"{req.module}: {req.test_type} Analysis Report",
        author=req.author,
        sections=sections,
        apa_results=apa_results,
    )

    return generate_report(report_req)
